import test from 'node:test';
import assert from 'node:assert/strict';
import { parseLrc } from '../tools/lib/lrc.mjs';

const sample = `[al:NCE1]
[ar:New Concept English]
[ti:Excuse Me]
[by:Generated by iChochy]
[00:00.61]Lesson 1 | 第1课
[00:02.71]Excuse me! | 打扰一下！
[00:05.61]Listen to the tape then answer this question. | 听录音，然后回答这个问题。
[00:10.80]Whose handbag is it? | 这是谁的手提包？
[00:15.11]Excuse me! | 请问！
[00:16.66]Yes? | 怎么了？
[00:18.26]Is this your handbag? | 这是你的手提包吗？
`;

test('解析标题、课号、听力问题与正文', () => {
  const parsed = parseLrc(sample, { extractQuestion: false });
  assert.equal(parsed.title, 'Excuse Me');
  assert.equal(parsed.titleZh, '打扰一下！');
  assert.equal(parsed.lessonNumber, 1);
  assert.equal(parsed.question, 'Whose handbag is it?');
  assert.equal(parsed.sentences.length, 3);
  assert.equal(parsed.sentences[0].en, 'Excuse me!');
  assert.equal(parsed.sentences[0].t, 15.11);
  assert.equal(parsed.sentences[1].zh, '怎么了？');
});

test('只跳过第一次标题句，不吞掉对话里的重复句', () => {
  const parsed = parseLrc(sample, { extractQuestion: false });
  assert.equal(parsed.sentences.filter((sentence) => sentence.en === 'Excuse me!').length, 1);
});

test('第二册起把首句问句识别为课前问题', () => {
  const text = `[ti:A Private Conversation]
[00:09.77]Why did the writer complain to the people behind him? | 作者为什么要抱怨？
[00:15.91]Last week I went to the theatre. | 上周我去了剧院。
`;
  const parsed = parseLrc(text, { extractQuestion: true });
  assert.equal(parsed.title, 'A Private Conversation');
  assert.equal(parsed.question, 'Why did the writer complain to the people behind him?');
  assert.equal(parsed.sentences.length, 1);
});

test('过滤广告、空行，并保留缺失译文', () => {
  const text = `[ti:Test]
[00:01.00]新概念英语学习软件：http://www.tysoft.net/
[00:02.77]
[00:03.00]Hello there.
`;
  const parsed = parseLrc(text, { extractQuestion: true });
  assert.equal(parsed.sentences.length, 1);
  assert.equal(parsed.sentences[0].zh, '');
});

test('支持全角分隔符', () => {
  const text = `[ti:Test]
[00:01.00]Good morning!｜早上好！
`;
  const parsed = parseLrc(text, { extractQuestion: true });
  assert.equal(parsed.sentences[0].zh, '早上好！');
});
